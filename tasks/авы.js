let день = "понедельник"
switch (день) {
  case 'понедельник':
    console.log('Сегодня первый день недели');
    break
  case 'вторник':
    console.log('Второй день недели');

  case 'среда':
    console.log('Среда — середина недели');
    break
  default:
    console.log('Это не один из дней недели');
}